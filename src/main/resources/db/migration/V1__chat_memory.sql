CREATE TABLE chat_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_id BIGINT NOT NULL, message_id BIGINT NOT NULL, thread_id BIGINT,
 sender_user_id BIGINT, sender_username TEXT, sender_display_name TEXT,
 sender_is_bot BOOLEAN NOT NULL, direction VARCHAR(16) NOT NULL CHECK(direction IN ('INCOMING','OUTGOING')),
 reply_to_message_id BIGINT, message_type VARCHAR(32) NOT NULL, text_content TEXT,
 telegram_date TIMESTAMPTZ NOT NULL, edited_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(chat_id,message_id));
CREATE INDEX idx_chat_messages_recent ON chat_messages(chat_id,telegram_date DESC,message_id DESC);
CREATE INDEX idx_chat_messages_thread ON chat_messages(chat_id,thread_id,telegram_date DESC,message_id DESC);
CREATE TABLE chat_memory_settings(chat_id BIGINT PRIMARY KEY,capture_enabled BOOLEAN NOT NULL,updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
